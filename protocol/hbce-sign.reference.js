#!/usr/bin/env node
/**
 * HBCE Sign Reference — ED25519 signer for IPR AI Audit Trail
 *
 * Scope:
 * - Generates ED25519 keypairs for R&D and demo verification.
 * - Signs HBCE registry records using canonical JSON v1.
 * - Signs full HBCE ledger examples with issuer/operator separation.
 * - Produces real signatures compatible with hbce-verify.reference.js.
 *
 * Public boundary:
 * - R&D reference implementation only.
 * - Not a regulated certification tool.
 * - Not an eIDAS qualified trust service.
 * - Not a public authority signing service.
 * - Not a custodial key-management system.
 *
 * Product hierarchy:
 * - IPR is the first operational product.
 * - IPR AI Audit Trail is the first MVP.
 * - HBCE is the governance ecosystem.
 * - JOKER-C2 is the runtime demonstrator.
 * - MATRIX is the wider architectural framework.
 *
 * Security rule:
 * - Private keys generated by this script must remain local.
 * - Do not commit private key envelopes to a public repository.
 * - Public keys may be published only when intentionally used for verification.
 *
 * Typical IPR audit workflow:
 *   node protocol/hbce-sign.reference.js --keygen issuer > protocol/keys/issuer.ed25519.private.json
 *   node protocol/hbce-sign.reference.js --keygen operator > protocol/keys/operator.ed25519.private.json
 *
 *   node protocol/hbce-verify.reference.js protocol/hbce-registry-ledger.example.json --rebuild > protocol/hbce-registry-ledger.rebuilt.json
 *
 *   node protocol/hbce-sign.reference.js --sign-ledger \
 *     protocol/hbce-registry-ledger.rebuilt.json \
 *     protocol/keys/issuer.ed25519.private.json \
 *     protocol/keys/operator.ed25519.private.json \
 *     > protocol/hbce-registry-ledger.signed.json
 *
 *   node protocol/hbce-verify.reference.js protocol/hbce-registry-ledger.signed.json --check-chain
 *   node protocol/hbce-verify.reference.js protocol/hbce-registry-ledger.signed.json --verify-entity IPR-AI-AUDIT-0001 --allow-rnd-status
 *   node protocol/hbce-verify.reference.js protocol/hbce-registry-ledger.signed.json --verify-event EVT-IPR-HUMAN-VALIDATION-0001 --allow-rnd-status
 */

const fs = require("fs");
const crypto = require("crypto");

// -----------------------------------------------------------------------------
// CLI helpers
// -----------------------------------------------------------------------------

const argv = process.argv.slice(2);

function has(flag) {
  return argv.includes(flag);
}

function idx(flag) {
  return argv.indexOf(flag);
}

function argAfter(flag) {
  const index = idx(flag);
  if (index === -1) return null;
  return argv[index + 1] || null;
}

function die(message, code = 1) {
  console.error(message);
  process.exit(code);
}

function isNonEmptyString(value) {
  return typeof value === "string" && value.trim().length > 0;
}

function readJsonFile(filePath, label) {
  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch {
    die(`Cannot read valid JSON ${label}: ${filePath}`);
  }
}

function writeJson(value) {
  process.stdout.write(`${JSON.stringify(value, null, 2)}\n`);
}

// -----------------------------------------------------------------------------
// Canonical JSON
// -----------------------------------------------------------------------------

function canonicalize(value) {
  if (value === null) return null;

  if (Array.isArray(value)) {
    return value.map(canonicalize);
  }

  if (typeof value === "object") {
    const output = {};

    for (const key of Object.keys(value).sort()) {
      output[key] = canonicalize(value[key]);
    }

    return output;
  }

  return value;
}

function canonicalBytes(value) {
  return Buffer.from(JSON.stringify(canonicalize(value)), "utf8");
}

/**
 * Signature and hash material must match hbce-verify.reference.js.
 *
 * Excluded fields:
 * - prev_record_sha256
 * - record_sha256
 * - issuer.signature
 * - operator.signature
 * - record_signature.signature
 */
function stripForSignature(record) {
  const output = JSON.parse(JSON.stringify(record));

  delete output.prev_record_sha256;
  delete output.record_sha256;

  if (output.issuer && typeof output.issuer === "object") {
    delete output.issuer.signature;
  }

  if (output.operator && typeof output.operator === "object") {
    delete output.operator.signature;
  }

  if (output.record_signature && typeof output.record_signature === "object") {
    delete output.record_signature.signature;
  }

  return output;
}

// -----------------------------------------------------------------------------
// Key envelope
// -----------------------------------------------------------------------------

function generateEd25519KeyEnvelope(name) {
  if (!isNonEmptyString(name)) {
    die("Missing key name.");
  }

  const { publicKey, privateKey } = crypto.generateKeyPairSync("ed25519");

  const publicKeySpkiDer = publicKey.export({
    type: "spki",
    format: "der"
  });

  const privateKeyPkcs8Der = privateKey.export({
    type: "pkcs8",
    format: "der"
  });

  return {
    proto: "HBCE-KEY-v1",
    kind: "ED25519_KEYPAIR",
    scope: "RND_REFERENCE_KEYPAIR",
    name,
    encoding: "base64",
    public_key_format: "spki-der",
    private_key_format: "pkcs8-der",
    public_key: publicKeySpkiDer.toString("base64"),
    private_key_pkcs8: privateKeyPkcs8Der.toString("base64"),
    created_at: new Date().toISOString(),
    security_notice: "Keep this private key envelope local. Do not commit it to a public repository."
  };
}

function exportPublicKeyEnvelope(privateEnvelopePath) {
  const key = loadKeyEnvelope(privateEnvelopePath);

  return {
    proto: "HBCE-KEY-v1",
    kind: "ED25519_PUBLIC_KEY",
    scope: "RND_REFERENCE_PUBLIC_KEY",
    name: key.env.name,
    encoding: "base64",
    public_key_format: "spki-der",
    public_key: key.env.public_key,
    exported_at: new Date().toISOString()
  };
}

function loadKeyEnvelope(filePath) {
  const envelope = readJsonFile(filePath, "key envelope");

  if (!envelope || envelope.proto !== "HBCE-KEY-v1" || envelope.kind !== "ED25519_KEYPAIR") {
    die(`Invalid key envelope: ${filePath}`);
  }

  if (envelope.encoding !== "base64") {
    die(`Unsupported key encoding in ${filePath}. Expected base64.`);
  }

  if (!isNonEmptyString(envelope.public_key) || !isNonEmptyString(envelope.private_key_pkcs8)) {
    die(`Missing public or private key material in ${filePath}.`);
  }

  let publicKey;
  let privateKey;

  try {
    publicKey = crypto.createPublicKey({
      key: Buffer.from(envelope.public_key, "base64"),
      format: "der",
      type: "spki"
    });

    privateKey = crypto.createPrivateKey({
      key: Buffer.from(envelope.private_key_pkcs8, "base64"),
      format: "der",
      type: "pkcs8"
    });
  } catch {
    die(`Cannot parse ED25519 key material in ${filePath}.`);
  }

  return {
    env: envelope,
    publicKey,
    privateKey
  };
}

// -----------------------------------------------------------------------------
// Signing
// -----------------------------------------------------------------------------

function signBytesEd25519(privateKey, bytes) {
  return crypto.sign(null, bytes, privateKey);
}

function ensureIssuerBlock(record, keyEnvelope) {
  if (!record.issuer || typeof record.issuer !== "object") {
    record.issuer = {};
  }

  if (!isNonEmptyString(record.issuer.name)) {
    record.issuer.name = "HERMETICUM B.C.E. S.r.l.";
  }

  record.issuer.sign_alg = "ED25519";
  record.issuer.pubkey = keyEnvelope.public_key;
}

function ensureOperatorBlock(record, keyEnvelope) {
  if (!record.operator || typeof record.operator !== "object") {
    record.operator = {};
  }

  if (!isNonEmptyString(record.operator.operator_id)) {
    record.operator.operator_id = "IPR-OP-RND-0001";
  }

  record.operator.sign_alg = "ED25519";
  record.operator.pubkey = keyEnvelope.public_key;
}

function signRecordWithRole(inputRecord, keyEnvelopePath, role) {
  if (role !== "issuer" && role !== "operator") {
    die(`Unknown signer role: ${role}. Expected issuer or operator.`);
  }

  const { env, privateKey } = loadKeyEnvelope(keyEnvelopePath);
  const output = JSON.parse(JSON.stringify(inputRecord));

  if (role === "issuer") {
    ensureIssuerBlock(output, env);
  }

  if (role === "operator") {
    ensureOperatorBlock(output, env);
  }

  const material = stripForSignature(output);
  const signature = signBytesEd25519(privateKey, canonicalBytes(material)).toString("base64");

  if (role === "issuer") {
    output.issuer.signature = signature;
  }

  if (role === "operator") {
    output.operator.signature = signature;
  }

  return output;
}

function signLedger(ledgerPath, issuerKeyPath, operatorKeyPath) {
  const ledger = readJsonFile(ledgerPath, "ledger");

  if (!ledger || ledger.proto !== "HBCE-LEDGER-v1" || !Array.isArray(ledger.records)) {
    die("Ledger format invalid: expected proto=HBCE-LEDGER-v1 and records array.");
  }

  const output = JSON.parse(JSON.stringify(ledger));

  output.signature_status = "SIGNED_REFERENCE_LEDGER";
  output.signature_note = "Records were signed with ED25519 reference keys. This does not transform the R&D ledger into a regulated certification, public authority registry, or eIDAS qualified trust service.";

  for (let index = 0; index < output.records.length; index += 1) {
    const record = output.records[index];

    if (record.kind === "IPR_EVENT_RECORD") {
      output.records[index] = signRecordWithRole(record, operatorKeyPath, "operator");
    } else if (
      record.kind === "IPR_ROOT_RECORD" ||
      record.kind === "IPR_DERIVED_RECORD" ||
      record.kind === "IPR_OPERATOR_RECORD"
    ) {
      output.records[index] = signRecordWithRole(record, issuerKeyPath, "issuer");
    } else {
      die(`Unsupported record kind at index ${index}: ${record.kind}`);
    }
  }

  return output;
}

// -----------------------------------------------------------------------------
// Main
// -----------------------------------------------------------------------------

if (has("--keygen")) {
  const name = argAfter("--keygen");

  if (!name) {
    die("Usage: --keygen <name>");
  }

  writeJson(generateEd25519KeyEnvelope(name));
  process.exit(0);
}

if (has("--export-public-key")) {
  const privateEnvelopePath = argAfter("--export-public-key");

  if (!privateEnvelopePath) {
    die("Usage: --export-public-key <private-key-envelope.json>");
  }

  writeJson(exportPublicKeyEnvelope(privateEnvelopePath));
  process.exit(0);
}

if (has("--sign-record")) {
  const startIndex = idx("--sign-record");
  const recordPath = argv[startIndex + 1];
  const keyPath = argv[startIndex + 2];
  const role = argAfter("--as");

  if (!recordPath || !keyPath || !role) {
    die("Usage: --sign-record <record.json> <key.json> --as issuer|operator");
  }

  const record = readJsonFile(recordPath, "record");
  writeJson(signRecordWithRole(record, keyPath, role));
  process.exit(0);
}

if (has("--sign-ledger")) {
  const startIndex = idx("--sign-ledger");
  const ledgerPath = argv[startIndex + 1];
  const issuerKeyPath = argv[startIndex + 2];
  const operatorKeyPath = argv[startIndex + 3];

  if (!ledgerPath || !issuerKeyPath || !operatorKeyPath) {
    die("Usage: --sign-ledger <ledger.json> <issuer.key.json> <operator.key.json>");
  }

  writeJson(signLedger(ledgerPath, issuerKeyPath, operatorKeyPath));
  process.exit(0);
}

die(
  [
    "Unknown or missing command.",
    "",
    "Commands:",
    "  --keygen <name>",
    "  --export-public-key <private-key-envelope.json>",
    "  --sign-record <record.json> <key.json> --as issuer|operator",
    "  --sign-ledger <ledger.json> <issuer.key.json> <operator.key.json>"
  ].join("\n")
);
